/**
 * Write one arm's project under `dir`, replacing whatever was there.
 *
 * `warmup`/`measured` are the PRD's run shape and are baked into the game so its own log can be
 * joined to the plan; the driver holds the same numbers.
 */
export function writeProject(dir, arm, { warmup = 120, measured = 1000 } = {}) {
  const spec = ARMS[arm];
  const write = (relative, contents) => {
    rmSync(join(dir, relative), { force: true });
    writeFileSync(join(dir, relative), contents);
  };
  mkdirSync(join(dir, "src", "ui"), { recursive: true });

  write(
    "package.json",
    `${JSON.stringify({ name: `tn-bench-${arm.replaceAll(/-/gu, "")}`, version: "0.0.0", private: true, type: "module" }, null, 2)}\n`,
  );
  write("threenative.config.ts", CONFIG_TS(arm, spec.renderer));
  write("vite.config.ts", VITE_TS);
  write("src/game.ts", GAME_TS(warmup, measured));
  if (spec.mode !== "none") {
    write("src/ui/Hud.tsx", HUD_TSX);
    write("src/ui/hud.css", CSS);
    write("src/ui/main.tsx", spec.page === true ? MAIN_TSX_WEB : MAIN_TSX_CSS);
  }
  write("src/native.tsx", spec.mode === "none" ? NATIVE_TS_UI_OFF : NATIVE_TSX(spec.mode));
  return dir;
}
