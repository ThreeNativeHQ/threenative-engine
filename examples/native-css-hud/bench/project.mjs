// Generate one tiny native project per measurement arm.
//
// The projects are the crate's own bench HUD (`packages/runtime-native/native/css-ui/examples/bench.rs`:
// 100 rows of (1 row + 9 cells) = 1,000 elements, text in every cell, classes row/cell/hot) over the
// example's cube scene, wired the way `corpus/project.mjs` wires a fixture: a native entry that
// mounts the tree through `createCssUiRoot()`, and a plain stylesheet imported by `src/ui/main.tsx`
// so Vite emits the sheet the engine resolves.
//
// Everything written here is build output. It lives under `bench/out/<arm>/dist/` on purpose: the
// repo's Biome config ignores `dist/`, and a generated project is a mirror of a page, not
// application code — the same reason `corpus/desktop.mjs` nests its projects there.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The arms, and the host each one is packaged against. `ui-off` never stages a UI at all. */
export const ARMS = {
  "ui-off": {
    renderer: "native",
    host: "tn-linux",
    mode: "none",
    note: 'the same cube game with no UI module and ui.renderer "native": no overlay, no UI bundle, no second process',
  },
  "native-css-static": {
    renderer: "native-css",
    host: "tn-linux",
    mode: "static",
    note: "1,000-node HUD, rendered once and never touched again",
  },
  "native-css-10pct": {
    renderer: "native-css",
    host: "tn-linux",
    mode: "10pct",
    note: "90 of the 900 cell texts (10%) change value every 6th frame",
  },
  "native-css-active": {
    renderer: "native-css",
    host: "tn-linux",
    mode: "active",
    note: "a 4 s background-color transition on those same 90 cells, re-triggered every 30 frames",
  },
  "web-overlay": {
    renderer: "web",
    host: "tn-linux-both",
    mode: "static",
    page: true,
    note: "the same HUD through react-dom on the both-backends host (static: an A/B for the static arm)",
  },
};

/**
 * The stylesheet, one byte-identical sheet for every arm so the arms differ only in what changes.
 *
 * The first three rules are the crate bench's own sheet. The transition is the active arm's: the
 * engine keeps repainting while a transition runs (`CssUi::render` returns early only when nothing
 * is dirty *and* no transition is in flight), so a long duration re-triggered every 30 frames makes
 * the repaint-per-frame case continuous instead of a 2 Hz flip. Inert in the other arms, which
 * never change a class.
 */
const CSS = `.row{display:flex;gap:4px;margin:2px 8px}
.cell{width:60px;height:14px;background:#334155;color:#e2e8f0;font-size:10px;overflow:hidden;transition:background-color 4000ms linear}
.hot{background:#2563eb}
`;

/** The crate's bench HUD as React: the same elements, the same classes, the same text density. */
const HUD_TSX = `/**
 * GENERATED by bench/project.mjs — do not edit.
 *
 * The crate's own bench HUD (packages/runtime-native/native/css-ui/examples/bench.rs), as React:
 * 100 rows of (1 row + 9 cells) = 1,000 elements with text in every cell and the classes
 * row/cell/hot. A fragment, not a wrapper, so the element count is exactly the crate's.
 */
const ROWS = 100;
const COLS = 9;
/** Every tenth cell: 90 of the 900 texts, and 90 of the 1,000 elements. The PRD's 10%. */
const TENTH = 10;

/**
 * @param kick  increments once per mutation burst; rewrites the text of the 90 tenth cells, so
 *              exactly 10% of the texts differ from the previous commit and 90% of the tree is
 *              byte-identical to it.
 * @param phase increments once per mutation burst in the active arm; flips \`hot\` on those same
 *              90 cells, and the sheet's transition is what keeps painting between the flips.
 */
export function Hud({ kick, phase }: { kick: number; phase: number }): React.ReactElement {
  const rows = [];
  for (let r = 0; r < ROWS; r += 1) {
    const cells = [];
    for (let c = 0; c < COLS; c += 1) {
      const tenth = (r * COLS + c) % TENTH === 0;
      const text = tenth ? \`r\${r}c\${c}#\${kick}\` : \`r\${r}c\${c}\`;
      const hot = tenth && phase % 2 === 1;
      cells.push(<div key={c} className={hot ? "cell hot" : "cell"}>{text}</div>);
    }
    rows.push(<div key={r} className="row">{cells}</div>);
  }
  return <>{rows}</>;
}
`;

const GAME_TS = (warmup, measured) => `/**
 * GENERATED by bench/project.mjs — do not edit.
 *
 * The example's cube scene, unchanged, plus the bench's own evidence: one line a second carrying
 * the frame count and whatever the HUD has published. \`posts\`/\`ops\` are the React root's counters
 * (-1 on the ui-off arm, which has no root), so a run that mounted no UI says so in its own log
 * instead of reading as one that painted nothing.
 */
import { type ICtx, Scene, defineGame } from "@threenative/core";
import { BoxGeometry, Color, Mesh, MeshStandardMaterial, PointLight } from "three";

/** The PRD's run shape, baked in so the log can be joined to the plan that asked for it. */
export const PLAN = { warmup: ${warmup}, measured: ${measured} };

export type BenchState = { frames: number };

/**
 * The one seam between the game's frame loop and the HUD.
 *
 * \`corpus/project.mjs\` runs its click ledger the other way — the UI calls into the game's store —
 * because a click originates in the UI. A dirty-frames arm originates in the game, so the game
 * calls the UI here instead, through a module-level sink that keeps \`game.ts\` and \`native.tsx\`
 * free of an import cycle.
 */
export const bench: {
  onFrame?: (frame: number) => void;
  report?: () => { posts: number; ops: number; mutations: number };
} = {};

declare global {
  var canvas: HTMLCanvasElement | undefined;
}

const hostCanvas = globalThis.canvas;

class Cube extends Scene<BenchState> {
  static override readonly initialState: BenchState = { frames: 0 };

  override enter(ctx: ICtx<BenchState>) {
    ctx.scene.background = new Color(0x18181b);
    ctx.camera.position.set(2, 2, 3);
    ctx.camera.lookAt(0, 0, 0);
    const light = ctx.add(new PointLight(0xffffff, 40));
    light.position.set(4, 6, 8);
    const cube = ctx.add(new Mesh(new BoxGeometry(1, 1, 1), new MeshStandardMaterial()));
    return (frameCtx: ICtx<BenchState>, dt: number) => {
      cube.rotation.x += dt * 0.6;
      cube.rotation.y += dt;
      const frames = frameCtx.state.getState().frames + 1;
      // Zero-based, so \`frame % 6 === 0\` is the crate's cadence read from the game's own count.
      bench.onFrame?.(frames - 1);
      if (frames % 60 === 0) {
        const ui = bench.report?.();
        console.log(
          \`TN_BENCH:\${JSON.stringify({
            frames,
            posts: ui?.posts ?? -1,
            ops: ui?.ops ?? -1,
            mutations: ui?.mutations ?? -1,
          })}\`,
        );
      }
      frameCtx.state.set({ frames });
    };
  }
}

const game: ReturnType<typeof defineGame<BenchState>> = defineGame<BenchState>({
  canvas: hostCanvas,
  inputTarget: hostCanvas,
  scenes: { cube: Cube },
  start: "cube",
});

export default game;
`;

