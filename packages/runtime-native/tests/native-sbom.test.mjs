import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'vitest';

import { makeTempDirSync } from '../../../test-support/temp-dir.js';

import {
  collectReceipts,
  generateAll,
  generateLicenseInventory,
  lockHash,
  readLock,
} from '../scripts/generate-native-sbom.mjs';

test('should generate a complete deterministic CycloneDX document from the real lock', () => {
  // PRD-059 Phase 2 native-sbom gate. Every lock component appears exactly once
  // by package URL; every payload SHA/source revision is reachable; two runs
  // are byte-identical; no timestamp or absolute workstation path exists.
  const { sbom } = generateAll();
  const first = sbom;
  const { sbom: second } = generateAll();
  assert.equal(first, second, 'two runs must be byte-identical');
  assert.ok(!/\d{4}-\d{2}-\d{2}T\d{2}:/u.test(first), 'no timestamp in SBOM');
  assert.ok(!first.includes('/home/') && !first.includes('C:\\'), 'no absolute workstation path in SBOM');
  const document = JSON.parse(first);
  assert.equal(document.bomFormat, 'CycloneDX');
  assert.equal(document.specVersion, '1.5');
  const lock = readLock();
  const expectedPayloads = lock.components.flatMap((component) => component.payloads.map((payload) => payload.id)).sort();
  const actualRefs = document.components.map((component) => component['bom-ref']).sort();
  assert.deepEqual(actualRefs, expectedPayloads);
  // Negative control: remove one component after generation; the check below
  // (and --check in CI) exits nonzero and names it — exercised here by
  // asserting the shrunken document no longer covers the lock.
  const shrunken = { ...document, components: document.components.slice(1) };
  assert.ok(shrunken.components.length < actualRefs.length);
});

test('should fail when license evidence is absent changed or orphaned', async () => {
  // PRD-059 Phase 2 native-license-inventory gate. Set equality between lock
  // components and inventory components; exact SPDX/evidence match.
  const lock = readLock();
  const inventory = generateLicenseInventory(lock);
  assert.equal(inventory.components.length, lock.components.length);
  for (const row of inventory.components) {
    assert.ok(row.spdx.length > 0 && row.evidenceUrl.length > 0 && row.sourceRevision.length > 0);
    assert.ok(row.payloads.length > 0);
  }
  // Negative control: change one license tuple without regenerating; the
  // generator run against the mutated lock produces different bytes, so
  // --check against the old output fails.
  const mutated = JSON.parse(JSON.stringify(lock));
  mutated.components[0].license.spdx = 'CHANGED-0.0';
  const { generateLicenseInventory: regen } = await import('../scripts/generate-native-sbom.mjs');
  assert.notDeepEqual(regen(mutated), inventory);
});

test('should refuse stale acquisition receipts', async () => {
  // A receipt written against a different lock hash is stale evidence, not a
  // passing input: collection with an expected hash rejects it by name.
  const root = makeTempDirSync('threenative-sbom-receipt-');
  const { mkdirSync } = await import('node:fs');
  mkdirSync(join(root, 'wgpu', '.threenative-receipts'), { recursive: true });
  writeFileSync(
    join(root, 'wgpu', '.threenative-receipts', 'receipt.json'),
    JSON.stringify({ lockHash: 'stale', payloads: [] }),
  );
  assert.throws(() => collectReceipts(root, 'current'), /TN_NATIVE_SBOM_RECEIPT_STALE.*wgpu/);
  // root is owned by makeTempDirSync: removed when the test finishes.
});

test('should expose deterministic generation through the CLI', () => {
  // --check compares regenerated bytes with supplied outputs; tested here
  // through the real CLI entrypoint, not the imported functions.
  const script = join(import.meta.dirname, '..', 'scripts', 'generate-native-sbom.mjs');
  const outDir = makeTempDirSync('threenative-sbom-cli-');
  const out = execFileSync(process.execPath, [script, '--out', outDir], { encoding: 'utf8' });
  assert.match(out, /Wrote SBOM/);
  assert.ok(readFileSync(join(outDir, 'native-dependencies.cdx.json'), 'utf8').includes('CycloneDX'));
  void lockHash;
});


test('canonical nested V8 receipt takes precedence over a stale cross-architecture sidecar', () => {
  const root = makeTempDirSync('threenative-sbom-v8-sidecar-');
  mkdirSync(join(root, 'v8', '.threenative-receipts'), { recursive: true });
  mkdirSync(join(root, '.threenative-receipts'));
  writeFileSync(join(root, '.threenative-receipts', 'v8-linux-arm64.json'),
    JSON.stringify({ dependency: 'v8', lockHash: 'stale', payloads: ['v8-linux-arm64'] }));
  writeFileSync(join(root, 'v8', '.threenative-receipts', 'receipt.json'),
    JSON.stringify({ dependency: 'v8', lockHash: 'current', payloads: ['v8-linux-x64'] }));
  const receipts = collectReceipts(root, 'current');
  assert.equal(receipts.length, 1);
  assert.deepEqual(receipts[0].payloads, ['v8-linux-x64']);
});
