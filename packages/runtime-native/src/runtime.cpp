    void dispatchResizeEvent(const platform::ResizeEventData& e) {
        // Update internal dimensions
        width_ = e.width;
        height_ = e.height;

        // Touch coordinates are normalized by SDL and scaled back up with getWindowSize(), so
        // the platform window has to track the canvas. A landscape-locked Android activity on
        // a portrait display resizes to 2400x1080 through this path while the platform size
        // stayed 1080x2400, which scaled every finger into the wrong half of the screen and
        // made a two-finger gesture read as two contacts on the same side.
        platform::syncWindowSize(e.width, e.height);

        // The swapchain is deliberately NOT reconfigured here, and `Runtime::resize()` — which
        // would — is still unreachable. Calling it from this path was tried and aborts the
        // process: a launch rotates the display twice before the first frame, and reconfiguring
        // the surface from inside the resize callback tears it down under the frame in flight.
        // A Pixel 8 died with signal 6 immediately after TN_NATIVE_SMOKE_FIRST_FRAME.
        //
        // Doing this correctly means deferring the reconfigure to a frame boundary, where no
        // surface texture is acquired. That is real work and is not attempted here; what is
        // recorded is that the obvious version is wrong.

        // Update window.innerWidth/innerHeight
        auto window = jsEngine_->getGlobal();
        jsEngine_->setProperty(window, "innerWidth", jsEngine_->newNumber(e.width));
        jsEngine_->setProperty(window, "innerHeight", jsEngine_->newNumber(e.height));

        auto event = jsEngine_->newObject();
        jsEngine_->setProperty(event, "type", jsEngine_->newString("resize"));

        dispatchToListeners("window", "resize", event);
    }

    js::JSValueHandle dispatchConstructedEvent(
        const std::string& target,
        js::JSValueHandle targetObject,
        const std::vector<js::JSValueHandle>& args
    ) {
        if (args.empty() || !jsEngine_->isObject(args[0])) {
            return jsEngine_->newBoolean(false);
        }

        const auto event = args[0];
        const auto typeValue = jsEngine_->getProperty(event, "type");
        if (jsEngine_->isUndefined(typeValue) || jsEngine_->isNull(typeValue)) {
            return jsEngine_->newBoolean(false);
        }
        const std::string eventType = jsEngine_->toString(typeValue);
        if (eventType.empty()) return jsEngine_->newBoolean(false);

        jsEngine_->setProperty(event, "target", targetObject);
        jsEngine_->setProperty(event, "currentTarget", targetObject);
        jsEngine_->setProperty(event, "eventPhase", jsEngine_->newNumber(2));

        const auto targetIt = eventListeners_.find(target);
        if (targetIt != eventListeners_.end()) {
            const auto typeIt = targetIt->second.find(eventType);
            if (typeIt != targetIt->second.end()) {
                const auto listeners = typeIt->second;
                for (const auto& listener : listeners) {
                    jsEngine_->call(listener.callback, targetObject, {event});
                    const auto stopped = jsEngine_->getProperty(event, "_immediatePropagationStopped");
                    if (!jsEngine_->isUndefined(stopped) && jsEngine_->toBoolean(stopped)) break;
                }
            }
        }

        jsEngine_->setProperty(event, "currentTarget", jsEngine_->newNull());
        jsEngine_->setProperty(event, "eventPhase", jsEngine_->newNumber(0));
        const auto defaultPrevented = jsEngine_->getProperty(event, "defaultPrevented");
        return jsEngine_->newBoolean(
            jsEngine_->isUndefined(defaultPrevented) || !jsEngine_->toBoolean(defaultPrevented)
        );
    }

    void removeEventListenerFromTarget(
        const std::string& target,
        const std::vector<js::JSValueHandle>& args
    ) {
        if (args.size() < 2) return;

        const std::string eventType = jsEngine_->toString(args[0]);
        const js::JSValueHandle callback = args[1];
        const bool useCapture = eventListenerCaptureFromArgs(args);
        const auto targetIt = eventListeners_.find(target);
        if (targetIt == eventListeners_.end()) return;

        const auto typeIt = targetIt->second.find(eventType);
        if (typeIt == targetIt->second.end()) return;

        auto& listeners = typeIt->second;
        for (auto it = listeners.begin(); it != listeners.end(); ++it) {
            if (it->useCapture != useCapture || !jsEngine_->isSameValue(it->callback, callback)) {
                continue;
            }
            jsEngine_->freeHandle(it->callback);
            listeners.erase(it);
            return;
        }
    }

    void dispatchToListeners(const std::string& target, const std::string& eventType, js::JSValueHandle event) {
        auto targetIt = eventListeners_.find(target);
        if (targetIt == eventListeners_.end()) {
            // Debug: no listeners registered for this target
            return;
        }

        auto typeIt = targetIt->second.find(eventType);
        if (typeIt == targetIt->second.end()) {
            // Debug: no listeners for this event type on this target
            return;
        }

        // Copy listeners in case they modify the list during iteration
        auto listeners = typeIt->second;

        for (const auto& listener : listeners) {
            std::vector<js::JSValueHandle> args = {event};
            jsEngine_->call(listener.callback, jsEngine_->newUndefined(), args);
        }
    }

    void setPointerLockElement(js::JSValueHandle element) {
        auto document = jsEngine_->getGlobalProperty("document");
        if (jsEngine_->isUndefined(document) || jsEngine_->isNull(document)) return;
        jsEngine_->setProperty(document, "pointerLockElement", element);
        auto event = jsEngine_->newObject();
        jsEngine_->setProperty(event, "type", jsEngine_->newString("pointerlockchange"));
        dispatchToListeners("document", "pointerlockchange", event);
        dispatchToListeners("window", "pointerlockchange", event);
        dispatchToListeners("canvas", "pointerlockchange", event);
    }

