    bool loadScript(const std::string& path) override {
        std::cout << "[Mystral] Loading script: " << path << std::endl;

        if (!moduleSystem_) {
            std::cerr << "[Mystral] Module system not initialized" << std::endl;
            return false;
        }

        // Store script path for reloading
        scriptPath_ = path;

        // Set up file watching if watch mode is enabled
        if (config_.watch && fs::getFileWatcher().isReady()) {
            if (watchId_ >= 0) {
                fs::getFileWatcher().unwatch(watchId_);
            }
            watchId_ = fs::getFileWatcher().watch(path, [this](const std::string& changedPath, fs::FileChangeType type) {
                if (type == fs::FileChangeType::Modified || type == fs::FileChangeType::Renamed) {
                    std::cout << "[HotReload] File changed: " << changedPath << std::endl;
                    reloadRequested_ = true;
                }
            });
            if (watchId_ >= 0) {
                std::cout << "[HotReload] Watching for changes: " << path << std::endl;
            }
        }

        return moduleSystem_->loadEntry(path);
    }

    bool evalScript(const std::string& code, const std::string& filename) override {
        std::cout << "[Mystral] Evaluating script: " << filename
                  << " (" << code.length() << " bytes)" << std::endl;

        if (!jsEngine_) {
            std::cerr << "[Mystral] No JavaScript engine available" << std::endl;
            return false;
        }

        return jsEngine_->evalScript(code.c_str(), filename.c_str());
    }

    bool reloadScript() override {
        if (scriptPath_.empty()) {
            std::cerr << "[HotReload] No script loaded to reload" << std::endl;
            return false;
        }

        std::cout << "[HotReload] Reloading script: " << scriptPath_ << std::endl;

        // Clear all pending timers
        clearAllTimers();

        // Clear all requestAnimationFrame callbacks
        for (auto& raf : rafCallbacks_) {
            jsEngine_->freeHandle(raf.callback);
        }
        rafCallbacks_.clear();

        // Clear module caches so script is re-read from disk
        if (moduleSystem_) {
            moduleSystem_->clearCaches();
        }

        // Reload the script
        bool success = moduleSystem_->loadEntry(scriptPath_);

        if (success) {
            std::cout << "[HotReload] Script reloaded successfully" << std::endl;
        } else {
            std::cerr << "[HotReload] Failed to reload script" << std::endl;
        }

        return success;
    }

private:
    void clearAllTimers() {
        clearSchedulerCallbacks();
#ifdef MYSTRAL_USE_LIBUV_TIMERS
        // Stop and clean up all libuv timers
        for (auto& [id, ctx] : uvTimers_) {
            if (ctx && !ctx->cancelled) {
                ctx->cancelled = true;
                uv_timer_stop(&ctx->handle);
                jsEngine_->freeHandle(ctx->callback);
                uv_close(reinterpret_cast<uv_handle_t*>(&ctx->handle), onTimerClose);
            }
        }
        // Note: Don't clear uvTimers_ here - onTimerClose will do that
        cancelledTimerIds_.clear();
        {
            std::lock_guard<std::mutex> lock(timerMutex_);
            while (!pendingTimerCallbacks_.empty()) {
                pendingTimerCallbacks_.pop();
            }
        }
#else
        // Clear std::chrono-based timers
        for (auto& timer : timerCallbacks_) {
            if (!timer.cancelled) {
                jsEngine_->freeHandle(timer.callback);
            }
        }
        timerCallbacks_.clear();
        cancelledTimerIds_.clear();
#endif
        nextTimerId_ = 1;
    }

    // A screenshot the mailbox asked for, waiting for its requested frame to be captured.
    std::string pendingScreenshotPath_;
    int pendingScreenshotTicks_ = 0;

    void processPlaytestScreenshotRequest() {
        const char* configuredRoot = std::getenv("TN_PLAYTEST_MAILBOX_ROOT");
        if (configuredRoot == nullptr || configuredRoot[0] == '\0') return;

        // Resolved once per root; the per-frame cost is one getenv plus one stat instead of an
        // ifstream open attempt inside every frame of a measurement run.
        static std::string cachedRequestPath;
        static std::string cachedRoot;
        if (cachedRoot != configuredRoot) {
            cachedRoot = configuredRoot;
            cachedRequestPath =
                (std::filesystem::path(cachedRoot) / "tn-playtest-screenshot-request.txt").string();
        }

        if (pendingScreenshotPath_.empty()) {
            std::error_code ec;
            if (!std::filesystem::exists(cachedRequestPath, ec)) return;
            std::ifstream request(cachedRequestPath, std::ios::binary);
            if (!request.is_open()) return;
            std::stringstream contents;
            contents << request.rdbuf();
            request.close();
            std::remove(cachedRequestPath.c_str());

            const std::string screenshotPath = contents.str();
            if (screenshotPath.empty() || screenshotPath.size() > 4096) return;
            pendingScreenshotPath_ = screenshotPath;
            pendingScreenshotTicks_ = 0;
        }

        // The capture lands at a present boundary after the request below; poll briefly rather
        // than failing on the first not-yet-captured tick. Bounded so a dead surface errors once,
        // like the single-shot failure this replaced.
        if (!webgpu_->isFrameScreenshotReady()) {
            webgpu_->requestFrameScreenshot();
            if (++pendingScreenshotTicks_ > 120) {
                std::cerr << "[Playtest] Native screenshot request failed: " << pendingScreenshotPath_ << std::endl;
                pendingScreenshotPath_.clear();
            }
            return;
        }
        const std::string screenshotPath = pendingScreenshotPath_;
        pendingScreenshotPath_.clear();
        if (!saveScreenshot(screenshotPath)) {
            std::cerr << "[Playtest] Native screenshot request failed: " << screenshotPath << std::endl;
        } else {
            // Consumed: the next request must wait for its own capture, not read this one.
            webgpu_->clearFrameScreenshotReady();
        }
    }

