    // ========================================================================
    // Main Loop
    // ========================================================================

    void run() override {
        // Check if script already called process.exit() during loading
        if (!running_) {
            localStorage_.flushIfDirty();
            std::cout << "[Mystral] Skipping main loop (process.exit already called)" << std::endl;
            return;
        }

        std::cout << "[Mystral] Starting main loop..." << std::endl;

        // Mock event removed - was causing rotation without mouse button press
        // sendMockPointerEvent()

        // In no-SDL mode, track consecutive idle frames to detect when script is done
        int idleFrames = 0;
        const int maxIdleFrames = 3;  // Exit after 3 frames with no work

        while (running_) {
            // pollEvents() handles:
            // - SDL event polling
            // - Timer callbacks (setTimeout/setInterval)
            // - Microtask queue (promises)
            // - requestAnimationFrame callbacks (renders frame)
            if (!pollEvents()) {
                break;
            }

            // In no-SDL (headless) mode, exit when there's no more work to do
            if (config_.noSdl) {
                bool hasWork = !rafCallbacks_.empty() || !schedulerCallbacks_.empty() || hasActiveTimers() ||
                               webtransport::hasActiveSessions();
                if (!hasWork) {
                    idleFrames++;
                    if (idleFrames >= maxIdleFrames) {
                        std::cout << "[Mystral] No-SDL mode: No more work, exiting cleanly" << std::endl;
                        running_ = false;
                        break;
                    }
                } else {
                    idleFrames = 0;
                }
            }
        }

        std::cout << "[Mystral] Main loop ended" << std::endl;
        // PRD-360 trailing endpoint for runs that exit the loop without
        // presenting (a plain `run` that calls process.exit, a never-ready
        // gate that quits). Once-only: a first-frame flush suppresses this one.
        // Runs killed by signal (SIGKILL/SIGTERM) never reach here by
        // construction — the harness must treat their missing line as failure.
        pumpSilence().flush(coldStartNowMs());
    }

    // Check if there are any active (non-cancelled) timers
    bool hasActiveTimers() const {
#ifdef MYSTRAL_USE_LIBUV_TIMERS
        for (const auto& [id, ctx] : uvTimers_) {
            if (ctx && !ctx->cancelled) {
                return true;
            }
        }
        return false;
#else
        for (const auto& timer : timerCallbacks_) {
            if (!timer.cancelled) {
                return true;
            }
        }
        return false;
#endif
    }

    void renderFrame() {
        // Rendering is now driven by JavaScript through requestAnimationFrame
        // The JS code calls context.getCurrentTexture(), creates render passes,
        // and submits command buffers which also presents the surface.
        // So we don't need to do anything here - just let JS drive.
    }

    /**
     * Rebuilds the presentation surface against the window the platform has now, and republishes
     * it to the bindings.
     *
     * Startup already solves this problem once: it waits for a valid `ANativeWindow`, checks it
     * with `ANativeWindow_getWidth`, creates the surface and configures it. Resume needs the same
     * sequence, which is what PRD-210 specified and did not carry, so this is that sequence
     * against a live device rather than a cold one.
     *
     * Non-Android targets keep their window across a minimize, so there is nothing to rebuild and
     * this reports success without touching anything.
     */
    bool revalidateSurfaceAfterResume() {
        if (platform::surfaceRevalidationDisabled()) {
            // The negative control, in the same binary as the fix: resume clears the paused flag
            // and nothing else, which is exactly what shipped before this change. Reachable only
            // through `debug.threenative.skip_surface_revalidate` / the environment variable.
            std::cerr << "[Mystral] TN_CONTROL_SKIP_SURFACE_REVALIDATE: resuming without "
                         "revalidating the surface; presents are expected to stop"
                      << std::endl;
            LOGE("TN_CONTROL_SKIP_SURFACE_REVALIDATE: resuming without revalidating the surface");
            return true;
        }

        if (platform::surfaceRevalidationForcedFailure()) {
            std::cerr << "[Mystral] TN_CONTROL_FORCE_SURFACE_REVALIDATE_FAILURE: refusing the "
                         "resume surface probe for the bounded-retry harness"
                      << std::endl;
            LOGE("TN_CONTROL_FORCE_SURFACE_REVALIDATE_FAILURE: resume probe forced to fail");
            return false;
        }

#if defined(__ANDROID__)
        if (!webgpu_) return false;

        SDL_Window* sdlWindow = platform::getSDLWindow();
        if (!sdlWindow) {
            std::cerr << "[Mystral] Resume found no SDL window" << std::endl;
            return false;
        }

        // The five-second resume window is owned by pollEvents(), which can retry this probe and
        // name every attempt. Keeping this helper to one probe means a failed first lookup does not
        // spend the whole window before the retry policy gets a chance to run.
        void* nativeWindow = nullptr;
        int32_t windowWidth = 0;
        int32_t windowHeight = 0;
        const int maxWaitAttempts = 1;
        for (int attempt = 0; attempt < maxWaitAttempts; attempt += 1) {
            SDL_Event event;
            while (SDL_PollEvent(&event)) {
                if (event.type == SDL_EVENT_QUIT) return false;
            }
            void* candidate = SDL_GetPointerProperty(SDL_GetWindowProperties(sdlWindow),
                SDL_PROP_WINDOW_ANDROID_WINDOW_POINTER, nullptr);
            if (candidate) {
                ANativeWindow* anw = (ANativeWindow*)candidate;
                windowWidth = ANativeWindow_getWidth(anw);
                windowHeight = ANativeWindow_getHeight(anw);
                if (windowWidth > 0 && windowHeight > 0) {
                    nativeWindow = candidate;
                    break;
                }
            }
        }

        if (!nativeWindow) {
            std::cerr << "[Mystral] Resume found no valid ANativeWindow after "
                      << maxWaitAttempts << " attempts" << std::endl;
            return false;
        }

        void* previous = webgpu_->getSurfaceNativeHandle();
        // Always rebuilt, never compared: Android reuses window addresses, so an unchanged pointer
        // is not evidence that the window survived, and a rebuild is what startup does anyway.
        webgpu::detachSurfaceForRebuild(bindingsState_);
        if (!webgpu_->rebuildSurface(nativeWindow, webgpu::Context::PLATFORM_ANDROID)) return false;

        platform::getWindowSize(&width_, &height_);
        if (width_ <= 0 || height_ <= 0) {
            width_ = static_cast<int>(windowWidth);
            height_ = static_cast<int>(windowHeight);
        }
        if (!webgpu_->configureSurface(width_, height_,
                                       config_.vsync && !platform::presentUncapped()))
            return false;

        webgpu::republishSurface(bindingsState_, webgpu_->getSurface(),
                                 webgpu_->getPreferredFormat(), webgpu_->getPresentMode(),
                                 static_cast<uint32_t>(width_), static_cast<uint32_t>(height_),
                                 webgpu_->getSurfaceNativeHandle());

        std::ostringstream marker;
        marker << "TN_LIFECYCLE_SURFACE:{\"event\":\"revalidated\",\"previousWindow\":\""
               << previous << "\",\"window\":\"" << nativeWindow << "\",\"width\":" << width_
               << ",\"height\":" << height_ << "}";
        std::cout << marker.str() << std::endl;
        LOGI("%s", marker.str().c_str());
        platform::refreshSafeAreaInsets();
        return true;
#else
        return true;
#endif
    }

    /** Names the failure loudly, on stderr and in logcat, before the loop stops. */
    void reportSurfaceRevalidationFailure() {
        const char* marker =
            "TN_LIFECYCLE_SURFACE_FAILED:{\"event\":\"revalidation-failed\"}";
        std::cerr << "[Mystral] " << marker
                  << " the presentation surface could not be rebuilt after resume; stopping the "
                     "loop rather than running frames that present nothing"
                  << std::endl;
        LOGE("%s", marker);
    }

    /**
     * Reports a pump phase that took long enough to matter, with the clock it really took.
     *
     * The frame meters answer "what did the frames cost", and they cannot answer "what happened
     * while there were no frames": a native startup iterates the loop a handful of times in forty
     * seconds, and a window that closes every 300 frames never covers that stretch. This says so
     * from the one place that knows - the phase itself. The threshold is deliberately high: this is
     * a stall report, not a profiler, and it stays silent on a healthy run.
     */
    struct SlowPhaseWatch {
        const char* phase;
        std::chrono::steady_clock::time_point began = std::chrono::steady_clock::now();
        explicit SlowPhaseWatch(const char* name) : phase(name) {}
        ~SlowPhaseWatch() {
            const double ms =
                static_cast<double>(std::chrono::duration_cast<std::chrono::microseconds>(
                                        std::chrono::steady_clock::now() - began)
                                        .count()) /
                1000.0;
            if (ms >= 250.0)
                std::cout << "TN_SLOW_PHASE:{\"phase\":\"" << phase << "\",\"ms\":" << ms
                          << ",\"atMs\":" << coldStartNowMs() << "}" << std::endl;
        }
    };

    bool pollEvents() override {
        // PRD-360 pump-silence observation: one entry stamp on the launch clock,
        // before every early return. Two steady_clock reads per entry; no
        // scheduling, quality, or scene-work change.
        pumpSilence().notePumpEntry(coldStartNowMs());
        SlowPhaseWatch iterationWatch("pollEvents");
        // Each frame's between-callbacks time is metered into named sub-phases (TN_HOST_GAP).
        // Segments bracket the existing calls; nothing here changes order or behaviour.
        hostGapMeter_.begin(HostGapMeter::kEvents);
        // Poll SDL events through our platform layer (skip in no-SDL mode)
        if (!config_.noSdl) {
            if (!platform::pollEvents()) {
                hostGapMeter_.end(HostGapMeter::kEvents);
                running_ = false;
                return false;
            }
        }

        // Drain the lifecycle markers the watch queued. The watch runs on SDL's sending thread —
        // on Android, the thread that is about to park the pump — so it only enqueues; the text
        // is written here, by the thread that owns stdio.
        drainLifecycleMarkers();

        if (platform::isTerminating()) {
            hostGapMeter_.end(HostGapMeter::kEvents);
            std::cout << "[Mystral] Lifecycle terminal event; stopping the loop" << std::endl;
            running_ = false;
            return false;
        }

        // The desktop overlay's slice of the frame, taken BEFORE the pause check.
        //
        // The overlay is a sibling window: it follows the game window's moves, resizes, restacks
        // and — the reason this sits here — its unmapping. A minimised game parks this loop, so a
        // pump placed after the check would never see the unmap, and the HUD would stay on screen
        // over the desktop with its game gone. Android and iOS pump on their own UI threads and
        // need none of this.
        platform::pumpUiOverlay();
        hostGapMeter_.end(HostGapMeter::kEvents);

        if (!config_.noSdl && platform::isPaused()) {
            // No JavaScript, no beginFrame, no rAF, no endDawnFrame, no present. Timer firings
            // that came due are counted and dropped rather than replayed all at once on resume;
            // `FixedStepLoop` clamps the elapsed time on the TypeScript side either way.
            countAndDropDueTimers();
            // Input callbacks run inside platform::pollEvents(), so they can dirty localStorage
            // immediately before a lifecycle event pauses the loop. Persist that snapshot at this
            // boundary before the paused process can be reclaimed by a mobile OS.
            localStorage_.flushIfDirty();
            // A paused stretch is not a frame and must not leak into the next one's sample.
            hostGapMeter_.dropPartialFrame();
            // Desktop does not block its pump the way Android does, so without this the paused
            // loop would spin a core at full speed — a battery fix that costs battery.
            std::this_thread::sleep_for(std::chrono::milliseconds(16));
            return running_;
        }

        // Coming back from the background is not just "unset the paused flag". Android destroyed
        // the ANativeWindow while the app was away and handed back a new one, so the surface every
        // present writes to points at nothing until it is rebuilt. Ahead of any frame work,
        // because a frame drawn to the dead surface is the black screen this fixes.
        const int kResumeRevalidationMaxAttempts = 5;
        const auto kResumeRevalidationWindow = std::chrono::seconds(5);
        if (!config_.noSdl && platform::takeSurfaceRevalidationRequest()) {
            const auto retryStarted = std::chrono::steady_clock::now();
            const auto retryDeadline = retryStarted + kResumeRevalidationWindow;
            const auto retryDelay = std::chrono::milliseconds(1000);
            bool revalidated = false;
            int attempts = 0;
            for (int attempt = 1; attempt <= kResumeRevalidationMaxAttempts; ++attempt) {
                attempts = attempt;
                const bool attemptSucceeded = revalidateSurfaceAfterResume();
                revalidated = attemptSucceeded;
                const auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(
                    std::chrono::steady_clock::now() - retryStarted);
                std::ostringstream retryMarker;
                retryMarker << "TN_LIFECYCLE_SURFACE_RETRY:{\"event\":\"attempt\",\"attempt\":"
                             << attempt << ",\"maxAttempts\":" << kResumeRevalidationMaxAttempts
                             << ",\"elapsedMs\":" << elapsed.count() << ",\"result\":\""
                             << (attemptSucceeded ? "success" : "failed") << "\"}";
                std::cout << retryMarker.str() << std::endl;
                LOGI("%s", retryMarker.str().c_str());
                if (revalidated) break;

                const auto remaining = retryDeadline - std::chrono::steady_clock::now();
                if (attempt == kResumeRevalidationMaxAttempts ||
                    remaining <= std::chrono::steady_clock::duration::zero())
                    break;
                const auto sleepFor = std::min(
                    retryDelay,
                    std::chrono::duration_cast<std::chrono::milliseconds>(remaining));
                if (sleepFor.count() > 0) SDL_Delay(static_cast<Uint32>(sleepFor.count()));
            }
            if (!revalidated) {
                const auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(
                    std::chrono::steady_clock::now() - retryStarted);
                std::ostringstream exhaustedMarker;
                exhaustedMarker << "TN_LIFECYCLE_SURFACE_RETRY:{\"event\":\"exhausted\",\"attempts\":"
                                 << attempts << ",\"windowMs\":"
                                 << std::chrono::duration_cast<std::chrono::milliseconds>(
                                        kResumeRevalidationWindow)
                                        .count()
                                 << ",\"elapsedMs\":" << elapsed.count() << "}";
                std::cout << exhaustedMarker.str() << std::endl;
                LOGE("%s", exhaustedMarker.str().c_str());
                // Fail closed. A host that cannot get a surface back cannot present, and a loop
                // that keeps running without presenting is the defect wearing a different hat:
                // frames at 600/s, presents frozen, a black screen and nothing in the log.
                reportSurfaceRevalidationFailure();
                running_ = false;
                exitCode_ = 1;
                return false;
            }
        }

        // Memory-pressure notifications are queued by the lifecycle watch while this thread may
        // be parked in Android's lifecycle wait. Deliver them only after the pause gate and on the
        // JavaScript-owning thread, so a backgrounded loop still runs no JavaScript.
        drainMemoryTrimCallbacks();

        // Poll libuv event loop - process any ready I/O callbacks (non-blocking)
        // This handles async HTTP requests, file I/O, and libuv-based timers
        hostGapMeter_.begin(HostGapMeter::kIo);
        async::EventLoop::instance().runOnce();

        // Worker isolates enqueue from their own threads; only the game thread may enter the main
        // engine, so completions are delivered in this existing host I/O segment.
        workers::WorkerRegistry::instance().processWorkerMessages(jsEngine_.get());

        // PRD-327: pipeline compiles finish on a host pool and their promises settle here, for the
        // same reason and in the same segment — the compile ran on another thread, and only this
        // one may enter the engine.
        webgpu::drainAsyncBufferMaps(bindingsState_);
        webgpu::drainAsyncPipelineCompiles(bindingsState_);

        // Process completed async HTTP requests (invoke their JS callbacks)
        // This must be called after runOnce() to invoke callbacks safely on the main thread
        http::getAsyncHttpClient().processCompletedRequests();

        // Drive WebTransport QUIC sessions and dispatch their JS events (main thread). Keep this
        // out of the generic I/O sample so proof can charge the actual transport work separately.
        hostGapMeter_.end(HostGapMeter::kIo);
        hostGapMeter_.begin(HostGapMeter::kWebTransport);
        // The proof lane can inject a bounded delay into this exact measured segment. It is an
        // environment-only seam, never read by game code, and lets the CPU budget prove that a
        // slow native transport pass cannot be hidden inside the broader I/O sample.
        if (const char* delay = std::getenv("TN_NETWORKING_TEST_PROCESS_EVENTS_DELAY_MS")) {
            const std::string value(delay);
            if (value.size() <= 4 && !value.empty()) {
                unsigned milliseconds = 0;
                bool valid = true;
                for (char digit : value) {
                    if (digit < '0' || digit > '9') {
                        valid = false;
                        break;
                    }
                    milliseconds = milliseconds * 10 + static_cast<unsigned>(digit - '0');
                }
                if (valid && milliseconds <= 1000)
                    std::this_thread::sleep_for(std::chrono::milliseconds(milliseconds));
            }
        }
        webtransport::processEvents();
        hostGapMeter_.end(HostGapMeter::kWebTransport);

        // Process completed async file reads (queues their callbacks)
        // Note: We don't process the pending callbacks immediately because we might
        // still be in a nested callback stack. The callbacks will be processed next frame.
        hostGapMeter_.begin(HostGapMeter::kIo);
        fs::getAsyncFileReader().processCompletedReads();
        // Image decodes land here for the same reason file reads do: a worker may not touch V8.
        { SlowPhaseWatch watch("imageDecodeDrain"); webgpu::AsyncImageDecoder::instance().drain(); }

        // Process file watch events (for hot reload)
        fs::getFileWatcher().processPendingEvents();
        hostGapMeter_.end(HostGapMeter::kIo);

        // Dispatch source completion callbacks outside the SDL audio thread.
        hostGapMeter_.begin(HostGapMeter::kAudio);
        audio::processAudioEvents();
        hostGapMeter_.end(HostGapMeter::kAudio);

        // Check if hot reload was requested
        if (reloadRequested_) {
            reloadRequested_ = false;
            reloadScript();
        }

        // Execute timer callbacks (setTimeout, setInterval)
        hostGapMeter_.begin(HostGapMeter::kTimers);
        { SlowPhaseWatch watch("timerCallbacks"); executeTimerCallbacks(); }

        // Process any queued file callbacks that were deferred from previous frames
        // We process them here (after other callbacks) to ensure we're not in a nested callback stack
        { SlowPhaseWatch watch("fileCallbacks"); processPendingFileCallbacks(); }

        // Deliver whatever the UI posted since the last frame.
        { SlowPhaseWatch watch("uiMessages"); drainUiMessages(); }
        hostGapMeter_.end(HostGapMeter::kTimers);

        // Process microtask queue for promises
        hostGapMeter_.begin(HostGapMeter::kMicrotasks);
        { SlowPhaseWatch watch("microtasks"); processMicrotasks(); }
        { SlowPhaseWatch watch("schedulerCallbacks"); executeSchedulerCallbacks(); }
        hostGapMeter_.end(HostGapMeter::kMicrotasks);

        // A deliberate fault, after startup, only when a proof harness asked for one. This is the
        // lane that checks "a crash after startup leaves a tombstone" without waiting for an
        // intermittent bug to recur; `deliberateCrashFrameCount()` is 0 unless the debug property
        // or the environment variable says otherwise.
        if (deliberateCrashFrames_ < 0) deliberateCrashFrames_ = platform::deliberateCrashFrameCount();
        if (deliberateCrashFrames_ > 0) {
            framesSinceStart_ += 1;
            if (framesSinceStart_ >= deliberateCrashFrames_) platform::crashDeliberately();
        }

        // Begin frame — enables per-frame allocation tracking
        hostGapMeter_.begin(HostGapMeter::kPreFrame);
        jsEngine_->beginFrame();
        webgpu::beginDawnFrame(bindingsState_);
        hostGapMeter_.end(HostGapMeter::kPreFrame);

        // Execute requestAnimationFrame callbacks (renders a frame)
        { SlowPhaseWatch watch("animationFrames"); executeAnimationFrameCallbacks(); }

        // Replay the JS-recorded WebGPU frame while descriptor and upload handles are still live.
        { SlowPhaseWatch watch("endDawnFrame"); webgpu::endDawnFrame(bindingsState_); }
        // The replay boundary's own split (drain / replay / present / poll / other) was timed
        // inside endDawnFrame; fold it into this frame's sample.
        hostGapMeter_.recordEndFramePhases(
            bindingsState_->profiling.framePhaseDrainNs, bindingsState_->profiling.framePhaseReplayNs,
            bindingsState_->profiling.framePhasePresentNs, bindingsState_->profiling.framePhaseUiNs,
            bindingsState_->profiling.framePhaseGpuDrainNs,
            bindingsState_->profiling.framePhasePollNs, bindingsState_->profiling.framePhaseOtherNs);

        // Free non-protected handles only after the replay boundary consumed the frame stream.
        hostGapMeter_.begin(HostGapMeter::kHandles);
        jsEngine_->clearFrameHandles();
        hostGapMeter_.end(HostGapMeter::kHandles);

        // Desktop screenshot requests are serviced by the host after the frame has presented. This
        // is file polling only; the game does not receive a per-frame JS/C++ callback.
        hostGapMeter_.begin(HostGapMeter::kScreenshot);
        processPlaytestScreenshotRequest();
        hostGapMeter_.end(HostGapMeter::kScreenshot);

        hostGapMeter_.begin(HostGapMeter::kStorage);
        localStorage_.flushIfDirty();
        hostGapMeter_.end(HostGapMeter::kStorage);
        hostGapMeter_.closeFrame();

        return running_;
    }

