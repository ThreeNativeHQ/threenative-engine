    bool setupFetch() {
        if (!jsEngine_) return false;

        auto readHttpHeaders = [this](js::JSValueHandle optionsObject, http::HttpOptions& options) {
            const auto headers = jsEngine_->getProperty(optionsObject, "headers");
            if (jsEngine_->isUndefined(headers) || jsEngine_->isNull(headers) ||
                !jsEngine_->isObject(headers))
                return;
            const auto forEach = jsEngine_->getProperty(headers, "forEach");
            if (!jsEngine_->isFunction(forEach)) return;
            const auto callback = jsEngine_->newFunction(
                "__httpHeader",
                [this, &options](void*, const std::vector<js::JSValueHandle>& headerArgs) {
                    if (headerArgs.size() >= 2) {
                        const auto name = jsEngine_->toString(headerArgs[1]);
                        if (!name.empty()) options.headers[name] = jsEngine_->toString(headerArgs[0]);
                    }
                    return jsEngine_->newUndefined();
                });
            jsEngine_->call(forEach, headers, {callback});
            jsEngine_->freeHandle(callback);
        };

        // Native file reading function - uses SDL on Android for asset access
        jsEngine_->setGlobalProperty("__readFileSync",
            jsEngine_->newFunction("__readFileSync", [this](void* ctx, const std::vector<js::JSValueHandle>& args) {
                if (args.empty()) {
                    return jsEngine_->newNull();
                }

                std::string path = resolveFetchFilePath(jsEngine_->toString(args[0]));

                // Check embedded bundle first (if present)
                std::vector<uint8_t> embeddedData;
                if (vfs::readEmbeddedFile(path, embeddedData)) {
                    std::cout << "[Fetch] Read " << embeddedData.size() << " bytes from bundle: " << path << std::endl;
                    return jsEngine_->newArrayBuffer(embeddedData.data(), embeddedData.size());
                }

#if defined(__ANDROID__)
                // On Android, use SDL_IOFromFile which can read from assets
                std::vector<uint8_t> buffer;
                std::string error;
                if (!readAndroidAsset(path, buffer, error)) {
                    std::cerr << "[Fetch] " << error << std::endl;
                    return jsEngine_->newNull();
                }

                std::cout << "[Fetch] Read " << buffer.size() << " bytes from Android asset: " << path << std::endl;
                return jsEngine_->newArrayBuffer(buffer.data(), buffer.size());
#else
                // On other platforms, use std::ifstream
                std::ifstream file(path, std::ios::binary | std::ios::ate);
                if (!file.is_open()) {
                    std::cerr << "[Fetch] Failed to open file: " << path << std::endl;
                    return jsEngine_->newNull();
                }

                size_t size = file.tellg();
                file.seekg(0, std::ios::beg);

                std::vector<uint8_t> buffer(size);
                if (!file.read(reinterpret_cast<char*>(buffer.data()), size)) {
                    std::cerr << "[Fetch] Failed to read file: " << path << std::endl;
                    return jsEngine_->newNull();
                }

                std::cout << "[Fetch] Read " << size << " bytes from: " << path << std::endl;
                return jsEngine_->newArrayBuffer(buffer.data(), buffer.size());
#endif
            })
        );

        // Async file reading function - uses libuv thread pool for non-blocking I/O
        // Takes (path, callback) where callback receives (data, error)
        jsEngine_->setGlobalProperty("__readFileAsync",
            jsEngine_->newFunction("__readFileAsync", [this](void* ctx, const std::vector<js::JSValueHandle>& args) {
                if (args.size() < 2) {
                    std::cerr << "[Fetch Async] Missing arguments (need path, callback)" << std::endl;
                    return jsEngine_->newUndefined();
                }

                std::string path = resolveFetchFilePath(jsEngine_->toString(args[0]));

                // Keep the callback alive until the asynchronous read completes.
                const auto callback = jsEngine_->retainHandle(args[1]);

                // Capture jsEngine pointer for the callback
                auto* engine = jsEngine_.get();

                // Check embedded bundle first (synchronously - it's fast)
                std::vector<uint8_t> embeddedData;
                if (vfs::readEmbeddedFile(path, embeddedData)) {
                    std::cout << "[Fetch] Read " << embeddedData.size() << " bytes from bundle: " << path << std::endl;
                    // Queue callback for next tick instead of calling immediately
                    // This prevents stack overflow and matches browser async behavior
                    pendingFileCallbacks_.push({
                        callback,
                        std::move(embeddedData),
                        "" // no error
                    });
                    return jsEngine_->newUndefined();
                }

#if defined(__ANDROID__)
                std::string error;
                if (readAndroidAsset(path, embeddedData, error)) {
                    pendingFileCallbacks_.push({callback, std::move(embeddedData), ""});
                } else {
                    pendingFileCallbacks_.push({callback, {}, std::move(error)});
                }
                return jsEngine_->newUndefined();
#endif

                // Use the async file reader with libuv thread pool
                // The callback will be queued and invoked during processCompletedReads()
                fs::getAsyncFileReader().readFile(path, [this, callback](std::vector<uint8_t> data, std::string error) {
                    // This callback runs on the main thread during processCompletedReads()
                    // Queue the callback with data for processing in the main loop
                    pendingFileCallbacks_.push({
                        callback,
                        std::move(data),
                        std::move(error)
                    });
                });

                return jsEngine_->newUndefined();
            })
        );

        // Native HTTP request function
        jsEngine_->setGlobalProperty("__httpRequest",
            jsEngine_->newFunction("__httpRequest", [this, readHttpHeaders](void* ctx, const std::vector<js::JSValueHandle>& args) {
                if (args.empty()) {
                    return jsEngine_->newNull();
                }

                std::string url = jsEngine_->toString(args[0]);
                std::string method = "GET";
                std::vector<uint8_t> body;
                http::HttpOptions options;

                // Parse options object if provided
                if (args.size() > 1 && !jsEngine_->isUndefined(args[1])) {
                    auto optObj = args[1];

                    auto methodVal = jsEngine_->getProperty(optObj, "method");
                    if (!jsEngine_->isUndefined(methodVal)) {
                        method = jsEngine_->toString(methodVal);
                    }

                    readHttpHeaders(optObj, options);

                    auto bodyVal = jsEngine_->getProperty(optObj, "body");
                    if (!jsEngine_->isUndefined(bodyVal)) {
                        if (jsEngine_->isString(bodyVal)) {
                            std::string bodyStr = jsEngine_->toString(bodyVal);
                            body.assign(bodyStr.begin(), bodyStr.end());
                        } else {
                            // Try to get as ArrayBuffer
                            size_t size = 0;
                            void* data = jsEngine_->getArrayBufferData(bodyVal, &size);
                            if (data && size > 0) {
                                body.assign(static_cast<uint8_t*>(data), static_cast<uint8_t*>(data) + size);
                            }
                        }
                    }
                }

                std::cout << "[HTTP] " << method << " " << url << std::endl;

                // Perform HTTP request
                auto& client = http::getHttpClient();
                http::HttpResponse response = client.request(method, url, body, options);

                // Create result object
                auto result = jsEngine_->newObject();
                jsEngine_->setProperty(result, "ok", jsEngine_->newBoolean(response.ok));
                jsEngine_->setProperty(result, "status", jsEngine_->newNumber(response.status));
                jsEngine_->setProperty(result, "url", jsEngine_->newString(response.url.c_str()));

                if (!response.error.empty()) {
                    jsEngine_->setProperty(result, "error", jsEngine_->newString(response.error.c_str()));
                }

                // Set response data as ArrayBuffer
                if (!response.data.empty()) {
                    auto arrayBuffer = jsEngine_->newArrayBuffer(response.data.data(), response.data.size());
                    jsEngine_->setProperty(result, "data", arrayBuffer);
                } else {
                    jsEngine_->setProperty(result, "data", jsEngine_->newNull());
                }

                std::cout << "[HTTP] Response: " << response.status << " (" << response.data.size() << " bytes)" << std::endl;

                return result;
            })
        );

        // Async HTTP request function - uses libuv for non-blocking I/O
        // Takes (url, options, callback) where callback receives the result object
        jsEngine_->setGlobalProperty("__httpRequestAsync",
            jsEngine_->newFunction("__httpRequestAsync", [this, readHttpHeaders](void* ctx, const std::vector<js::JSValueHandle>& args) {
                if (args.size() < 3) {
                    std::cerr << "[HTTP Async] Missing arguments (need url, options, callback)" << std::endl;
                    return jsEngine_->newUndefined();
                }

                std::string url = jsEngine_->toString(args[0]);
                std::string method = "GET";
                std::vector<uint8_t> body;
                http::HttpOptions options;

                // Parse options object
                if (!jsEngine_->isUndefined(args[1]) && !jsEngine_->isNull(args[1])) {
                    auto optObj = args[1];

                    auto methodVal = jsEngine_->getProperty(optObj, "method");
                    if (!jsEngine_->isUndefined(methodVal)) {
                        method = jsEngine_->toString(methodVal);
                    }

                    readHttpHeaders(optObj, options);

                    auto bodyVal = jsEngine_->getProperty(optObj, "body");
                    if (!jsEngine_->isUndefined(bodyVal)) {
                        if (jsEngine_->isString(bodyVal)) {
                            std::string bodyStr = jsEngine_->toString(bodyVal);
                            body.assign(bodyStr.begin(), bodyStr.end());
                        } else {
                            size_t size = 0;
                            void* data = jsEngine_->getArrayBufferData(bodyVal, &size);
                            if (data && size > 0) {
                                body.assign(static_cast<uint8_t*>(data), static_cast<uint8_t*>(data) + size);
                            }
                        }
                    }
                }

                // Keep the callback alive until the asynchronous request completes.
                const auto callback = jsEngine_->retainHandle(args[2]);

                // Capture jsEngine pointer for the callback
                auto* engine = jsEngine_.get();

                // Start async request
                http::getAsyncHttpClient().request(method, url, body,
                    [engine, callback](http::HttpResponse response) {
                        // This runs on the main thread when the response arrives
                        // Create result object
                        auto result = engine->newObject();
                        engine->setProperty(result, "ok", engine->newBoolean(response.ok));
                        engine->setProperty(result, "status", engine->newNumber(response.status));
                        engine->setProperty(result, "url", engine->newString(response.url.c_str()));

                        if (!response.error.empty()) {
                            engine->setProperty(result, "error", engine->newString(response.error.c_str()));
                        }

                        if (!response.data.empty()) {
                            auto arrayBuffer = engine->newArrayBuffer(response.data.data(), response.data.size());
                            engine->setProperty(result, "data", arrayBuffer);
                        } else {
                            engine->setProperty(result, "data", engine->newNull());
                        }

                        // Call the JS callback with the result
                        std::vector<js::JSValueHandle> callbackArgs = { result };
                        engine->call(callback, engine->newUndefined(), callbackArgs);

                        // Unprotect the callback now that we're done
                        engine->freeHandle(callback);
                    },
                    options
                );

                return jsEngine_->newUndefined();
            })
        );

        // JavaScript fetch polyfill
        if (!evalRuntimeScript(*jsEngine_, "fetch-polyfill", "fetch-polyfill.js")) return false;
        std::cout << "[Mystral] Fetch API initialized (file://, http://, https://)" << std::endl;

        // --- WHATWG Streams -------------------------------------------------
        // Real (spec-shaped) ReadableStream / WritableStream / TransformStream
        // plus TextEncoderStream / TextDecoderStream. These back the
        // WebTransport API (so its readable/writable support pipeTo/pipeThrough,
        // tee and async iteration) and are also available to user code. Each is
        // guarded by typeof-undefined so a native engine implementation wins.
        if (!evalRuntimeScript(*jsEngine_, "streams-polyfill", "streams-polyfill.js")) return false;
        std::cout << "[Mystral] Web Streams API initialized (ReadableStream/WritableStream/TransformStream)" << std::endl;
        return true;
    }

    bool setupURL() {
        if (!jsEngine_) return false;

        const char* workerRollback = std::getenv("THREENATIVE_NATIVE_WORKER_ROLLBACK");
        const bool workerRollbackActive =
            workerRollback != nullptr && std::string(workerRollback) == "1";
        jsEngine_->setGlobalProperty(
            "__tnNativeWorkerRollbackActive", jsEngine_->newBoolean(workerRollbackActive));
        if (workerRollbackActive) {
            std::cerr << "TN_NATIVE_WORKER_ROLLBACK_ACTIVE: native worker acceptance is disabled"
                      << std::endl;
        }

        auto* workerRegistry = &workers::WorkerRegistry::instance();
        if (!workerRegistry->isAvailable()) {
            std::cerr << "TN_NATIVE_WORKER_UNAVAILABLE: worker sources were not linked" << std::endl;
            return false;
        }
        // The registry is a process-wide singleton and a previous Runtime in this process may have
        // closed it on teardown. This Runtime's workers are its own, so re-open it here.
        workerRegistry->open();

        jsEngine_->setGlobalProperty("__tnNativeWorkerCreate",
            jsEngine_->newFunction("__tnNativeWorkerCreate",
                [this, workerRegistry](void*, const std::vector<js::JSValueHandle>& args) {
                    if (args.empty() || !jsEngine_->isString(args[0])) {
                        jsEngine_->throwException(
                            "TN_NATIVE_WORKER_SOURCE_INVALID: classic Blob source must be text");
                        return jsEngine_->newNumber(-1);
                    }
                    const int workerId = workerRegistry->createWorker(jsEngine_->toString(args[0]));
                    if (workerId < 1) {
                        jsEngine_->throwException(
                            "TN_NATIVE_WORKER_UNAVAILABLE: worker thread creation failed");
                        return jsEngine_->newNumber(-1);
                    }
                    activeWorkerIds_.insert(workerId);
                    workerRegistry->registerCallback(workerId,
                        [this](int id, const workers::WorkerMessage& message) {
                            // processWorkerMessages may already have collected more than one
                            // completion. terminate() removes the id before joining, so a later
                            // collected completion cannot callback after termination.
                            if (activeWorkerIds_.count(id) == 0 || !jsEngine_) return;
                            auto dispatch = jsEngine_->getGlobalProperty("__tnNativeWorkerDispatch");
                            if (!jsEngine_->isFunction(dispatch)) return;
                            const std::string payload(message.payload.begin(), message.payload.end());
                            jsEngine_->call(dispatch, jsEngine_->newUndefined(), {
                                jsEngine_->newNumber(id),
                                jsEngine_->newNumber(static_cast<int>(message.type)),
                                jsEngine_->newString(payload.c_str()),
                            });
                        });
                    const std::string workerCreatedMarker =
                        "TN_NATIVE_WORKER_CREATED:{\"id\":" + std::to_string(workerId) +
                        ",\"engine\":\"" + jsEngine_->getName() + "\"}";
                    std::cout << workerCreatedMarker << std::endl;
                    return jsEngine_->newNumber(workerId);
                }));

        jsEngine_->setGlobalProperty("__tnNativeWorkerPost",
            jsEngine_->newFunction("__tnNativeWorkerPost",
                [this, workerRegistry](void*, const std::vector<js::JSValueHandle>& args) {
                    if (args.size() < 2) return jsEngine_->newBoolean(false);
                    const int workerId = static_cast<int>(jsEngine_->toNumber(args[0]));
                    if (activeWorkerIds_.count(workerId) == 0 || !jsEngine_->isString(args[1])) {
                        return jsEngine_->newBoolean(false);
                    }
                    const std::string payload = jsEngine_->toString(args[1]);
                    workers::WorkerMessage message;
                    message.type = workers::WorkerMessage::Type::MESSAGE;
                    message.payload.assign(payload.begin(), payload.end());
                    workerRegistry->postToWorker(workerId, std::move(message));
                    return jsEngine_->newBoolean(true);
                }));

        jsEngine_->setGlobalProperty("__tnNativeWorkerTerminate",
            jsEngine_->newFunction("__tnNativeWorkerTerminate",
                [this, workerRegistry](void*, const std::vector<js::JSValueHandle>& args) {
                    if (args.empty()) return jsEngine_->newUndefined();
                    const int workerId = static_cast<int>(jsEngine_->toNumber(args[0]));
                    activeWorkerIds_.erase(workerId);
                    workerRegistry->terminateWorker(workerId);
                    const std::string workerTerminatedMarker =
                        "TN_NATIVE_WORKER_TERMINATED:{\"id\":" + std::to_string(workerId) + "}";
                    std::cout << workerTerminatedMarker << std::endl;
                    return jsEngine_->newUndefined();
                }));

        // URL and URLSearchParams remain compatibility polyfills. Worker is now only a standard
        // JavaScript facade over the native registry; absence of these callbacks throws by name.
        if (!evalRuntimeScript(*jsEngine_, "url-worker-polyfill", "url-worker-polyfill.js")) return false;
        std::cout << "[Mystral] URL and native Worker facade initialized" << std::endl;
        return true;
    }

