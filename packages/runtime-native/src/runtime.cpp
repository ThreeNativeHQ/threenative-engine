    /**
     * Writes the markers the lifecycle watch queued, and reports the skipped timer firings
     * alongside the resume so a run says what the pause cost rather than leaving it to inference.
     */
    /**
     * The game end of the UI bridge.
     *
     * `@threenative/core/ui-layer` discovers its transport rather than being configured with
     * one, and these two globals are the whole contract on this side: `__tnUiPost` carries a
     * frame out to the overlay, and the runtime calls `__tnUiGameReceive` with each frame that
     * came back. Their names are declared once, in `UI_BRIDGE_GLOBALS`; a host that spells one
     * differently has no bridge at all, silently, which is why they are asserted by a test
     * rather than kept in step by hand.
     *
     * `__tnUiPost` returns false when no overlay is attached — a `renderer: "native"` game, or
     * a platform with no overlay yet. The UI layer reads that as "nobody is listening", which
     * is honest; it is not an error and it is not silence.
     */
    void setupUiBridge() {
        if (!jsEngine_) return;
        jsEngine_->setGlobalProperty("__tnUiPost",
            jsEngine_->newFunction("__tnUiPost", [this](void*, const std::vector<js::JSValueHandle>& args) {
                if (args.empty()) return jsEngine_->newBoolean(false);
                return jsEngine_->newBoolean(platform::postUiMessage(jsEngine_->toString(args[0])));
            }));
        jsEngine_->setGlobalProperty("__tnUiOverlayAttached",
            jsEngine_->newFunction("__tnUiOverlayAttached", [this](void*, const std::vector<js::JSValueHandle>&) {
                return jsEngine_->newBoolean(platform::uiOverlayAttached());
            }));
        // The native UI composite's cost, for the frame budget's `ui` phase (PRD-393 Phase 3).
        //
        // It is the *previous* frame's number. The composite runs inside `endDawnFrame`, which is
        // after every rAF callback has returned, so the frame being measured cannot report its own
        // composite cost from inside itself. One frame of skew on a phase whose whole purpose is a
        // p95 is not a measurement anyone can be misled by, and the alternative — inventing a JS
        // binding that blocks on the render thread — would cost more than the thing it measures.
        // Zero when there is no overlay, so a game with a native renderer reports a real zero
        // rather than an absent phase.
        jsEngine_->setGlobalProperty("__tnUiCompositeMs",
            jsEngine_->newFunction("__tnUiCompositeMs", [this](void*, const std::vector<js::JSValueHandle>&) {
                if (!bindingsState_) return jsEngine_->newNumber(0);
                return jsEngine_->newNumber(
                    static_cast<double>(bindingsState_->profiling.framePhaseUiNs) / 1'000'000.0);
            }));
    }

    /**
     * Deliver the frames the overlay queued, on the thread that owns JavaScript.
     *
     * The host enqueues from its own UI thread; nothing here may run there. Same shape as the
     * lifecycle markers above, and for the same reason.
     */
    /**
     * Apply a `tn:hit-regions` frame, or report that it was not one.
     *
     * Parsed here rather than through the JS engine because it must work before any game script
     * has connected its end of the bridge, and because the numbers go straight back out to the
     * platform. Fail closed: a malformed publication leaves the previous rectangles in place and
     * every later click is decided against rectangles that no longer exist, so it is named.
     */
    bool applyUiHitRegions(const std::string& frame) { return platform::applyUiHitRegionsFrame(frame); }

    void drainUiMessages() {
        if (!jsEngine_) return;
        std::string frame;
        while (platform::takeUiMessage(frame)) {
            // Hit regions stop at the host: it owns the hit test, and forwarding them to the
            // game would put a process hop in the input path for a reader that does not exist.
            // Same rule as the Android host, which applies them in Java for the same reason.
            if (applyUiHitRegions(frame)) continue;
            js::JSValueHandle receive = jsEngine_->getGlobalProperty("__tnUiGameReceive");
            if (!jsEngine_->isFunction(receive)) {
                // The game has not connected its end yet. Dropping is correct and must be
                // visible: a UI whose intents vanish looks exactly like a dead button.
                std::cout << "TN_UI_BRIDGE:{\"dropped\":\"no __tnUiGameReceive\"}" << std::endl;
                continue;
            }
            jsEngine_->call(receive, jsEngine_->getGlobal(), {jsEngine_->newString(frame.c_str())});
            if (jsEngine_->hasException()) {
                std::cerr << "[Mystral] UI bridge frame threw: " << jsEngine_->getException()
                          << std::endl;
            }
        }
    }

    void drainLifecycleMarkers() {
        std::string marker;
        while (platform::takeLifecycleMarker(marker)) {
            std::cout << marker << std::endl;
#if defined(__ANDROID__)
            __android_log_print(ANDROID_LOG_INFO, MYSTRAL_LOG_TAG, "%s", marker.c_str());
#endif
        }
        if (!platform::isPaused() && !countedPausedTimers_.empty()) {
            const uint64_t skipped = platform::takeDroppedTimerFirings();
            countedPausedTimers_.clear();
            std::cout << "TN_LIFECYCLE:{\"event\":\"catchUp\",\"skippedTimerFirings\":" << skipped
                      << "}" << std::endl;
        }
    }

    /**
     * Delivers queued trim levels after the pause gate and before the next frame's I/O work.
     *
     * Android invokes the lifecycle bridge on its UI thread, while JavaScript belongs to the
     * runtime thread. The queue preserves that ownership boundary and also means a backgrounded
     * app does not execute JavaScript just because the OS asked it to release memory.
     */
    void drainMemoryTrimCallbacks() {
        if (!jsEngine_) return;
        int level = 0;
        while (platform::takeMemoryTrimRequest(level)) {
            const auto callback = jsEngine_->getGlobalProperty("__tnOnTrimMemory");
            const bool callbackInstalled = jsEngine_->isFunction(callback);
            if (callbackInstalled) {
                jsEngine_->call(callback, jsEngine_->getGlobal(), {
                    jsEngine_->newNumber(level),
                });
                if (jsEngine_->hasException()) {
                    std::cerr << "[Mystral] __tnOnTrimMemory threw: " << jsEngine_->getException()
                              << std::endl;
                }
            }

            // The runtime owns the JS heap, so collect after the game had a chance to release its
            // own references in the optional callback. This is deliberately on the runtime thread;
            // V8/QuickJS/JSC are not entered from Android's UI callback.
            jsEngine_->gc();

            std::ostringstream marker;
            marker << "TN_LIFECYCLE_MEMORY_TRIM_CALLBACK:{\"level\":" << level
                   << ",\"callback\":" << (callbackInstalled ? "true" : "false")
                   << ",\"gc\":\"requested\"}";
            std::cout << marker.str() << std::endl;
            LOGI("%s", marker.str().c_str());
        }
    }

    /**
     * Counts, once per pause, each timer that came due while the loop was parked.
     *
     * Nothing is replayed: the libuv loop is not run while paused, and an interval reschedules
     * from `now`, so a ten-minute background costs at most one firing per timer rather than a
     * flood. `FixedStepLoop` clamps the simulation side of the same gap
     * (`packages/core/src/loop.ts`), which is asserted rather than rebuilt here.
     */
    void countAndDropDueTimers() {
#ifdef MYSTRAL_USE_LIBUV_TIMERS
        std::lock_guard<std::mutex> lock(timerMutex_);
        // The queue cannot grow while paused, so counting it once is the whole answer.
        if (countedPausedTimers_.count(0) == 0) {
            countedPausedTimers_.insert(0);
            for (size_t i = 0; i < pendingTimerCallbacks_.size(); i++)
                platform::noteDroppedTimerFiring();
        }
#else
        const auto now = PerformanceClock::now();
        for (const auto& timer : timerCallbacks_) {
            if (timer.cancelled || now < timer.targetTime) continue;
            if (countedPausedTimers_.insert(timer.id).second) platform::noteDroppedTimerFiring();
        }
        // A pause with no timers at all still has to leave a trace, or the resume marker cannot
        // tell "nothing was skipped" from "nobody looked".
        countedPausedTimers_.insert(0);
#endif
    }

    void executeTimerCallbacks() {
#ifdef MYSTRAL_USE_LIBUV_TIMERS
        // Process pending timer callbacks from libuv
        std::queue<PendingTimerCallback> toProcess;
        {
            std::lock_guard<std::mutex> lock(timerMutex_);
            std::swap(toProcess, pendingTimerCallbacks_);
        }

        while (!toProcess.empty()) {
            auto pending = std::move(toProcess.front());
            toProcess.pop();

            // Check if cancelled while waiting in queue
            if (cancelledTimerIds_.count(pending.id) > 0) {
                cancelledTimerIds_.erase(pending.id);
                continue;
            }

            // Call the callback
            std::vector<js::JSValueHandle> args;
            jsEngine_->call(pending.callback, jsEngine_->newUndefined(), args);

            // For setTimeout (intervalMs == 0), clean up the timer
            if (pending.intervalMs == 0) {
                auto it = uvTimers_.find(pending.id);
                if (it != uvTimers_.end()) {
                    jsEngine_->freeHandle(it->second->callback);
                    // uv_close is async - onTimerClose will erase from map when done
                    uv_close(reinterpret_cast<uv_handle_t*>(&it->second->handle), onTimerClose);
                }
            }
            // For setInterval, libuv automatically repeats - nothing to do
        }
#else
        // Fallback: std::chrono-based timer processing
        if (timerCallbacks_.empty()) return;

        const auto now = PerformanceClock::now();

        // Process timers - collect expired ones
        std::vector<TimerCallback> toExecute;
        std::vector<TimerCallback> remaining;

        for (auto& timer : timerCallbacks_) {
            if (timer.cancelled) {
                continue;  // Skip cancelled timers
            }

            if (now >= timer.targetTime) {
                toExecute.push_back(timer);
            } else {
                remaining.push_back(timer);
            }
        }

        timerCallbacks_ = std::move(remaining);

        // Execute expired timers
        for (auto& timer : toExecute) {
            // Call the callback
            std::vector<js::JSValueHandle> args;
            jsEngine_->call(timer.callback, jsEngine_->newUndefined(), args);

            if (timer.intervalMs > 0) {
                // Check if interval was cancelled during callback execution
                bool wasCancelled = false;
                for (const auto& t : timerCallbacks_) {
                    if (t.id == timer.id && t.cancelled) {
                        wasCancelled = true;
                        break;
                    }
                }
                // Also check cancelledTimerIds_ set
                if (cancelledTimerIds_.count(timer.id) > 0) {
                    wasCancelled = true;
                }

                if (!wasCancelled) {
                    // Re-schedule interval
                    timer.targetTime = now + std::chrono::milliseconds(timer.intervalMs);
                    timerCallbacks_.push_back(timer);
                } else {
                    jsEngine_->freeHandle(timer.callback);
                    cancelledTimerIds_.erase(timer.id);
                }
            } else {
                // setTimeout - release the callback and finish
                jsEngine_->freeHandle(timer.callback);
            }
        }
#endif
    }

    void processPendingFileCallbacks() {
        // Process pending file callbacks - these come from async file reads
        // We process them on the main thread to ensure JS context safety.
        //
        // Bounded in time and count, the way `executeSchedulerCallbacks` below is: one frame must
        // not own a whole asset burst. A native run of a real game measured a single `fileCallbacks`
        // phase of 846-1527 ms during launch — the reads are issued in parallel, so every completed
        // read arrives at once, and each callback copies its bytes into a fresh ArrayBuffer before
        // the game can continue. The work is the same either way; what changes is that the loading
        // screen gets a frame between batches instead of freezing through all of them.
        const auto deadline = std::chrono::steady_clock::now() + std::chrono::milliseconds(4);
        for (int count = 0; running_ && count < 256 && !pendingFileCallbacks_.empty(); ++count) {
            auto pending = std::move(pendingFileCallbacks_.front());
            pendingFileCallbacks_.pop();

            if (pending.error.empty()) {
                // Success - create ArrayBuffer and call callback with (data, null)
                auto dataVal = jsEngine_->newArrayBuffer(pending.data.data(), pending.data.size());
                auto errorVal = jsEngine_->newNull();
                std::vector<js::JSValueHandle> callbackArgs = { dataVal, errorVal };
                jsEngine_->call(pending.callback, jsEngine_->newUndefined(), callbackArgs);
            } else {
                // Error - call callback with (null, error)
                auto nullVal = jsEngine_->newNull();
                auto errorVal = jsEngine_->newString(pending.error.c_str());
                std::vector<js::JSValueHandle> callbackArgs = { nullVal, errorVal };
                jsEngine_->call(pending.callback, jsEngine_->newUndefined(), callbackArgs);
            }

            // Unprotect the callback now that we're done with it
            jsEngine_->freeHandle(pending.callback);
            // A callback may enqueue the next read; let its continuation run before the next one.
            processMicrotasks();
            if (std::chrono::steady_clock::now() >= deadline) break;
        }
    }

    void processMicrotasks() {
        jsEngine_->processMicrotasks();
    }

    void clearSchedulerCallbacks() {
        while (!schedulerCallbacks_.empty()) {
            if (jsEngine_) jsEngine_->freeHandle(schedulerCallbacks_.front());
            schedulerCallbacks_.pop();
        }
    }

    void executeSchedulerCallbacks() {
        // Tasks may enqueue their next continuation at the microtask checkpoint. Let cheap
        // chains advance without presenting a frame per task, but bound both time and count
        // so an unending chain cannot starve the next input/timer/render iteration.
        const auto deadline = std::chrono::steady_clock::now() + std::chrono::milliseconds(2);
        for (int count = 0; running_ && count < 1024 && !schedulerCallbacks_.empty(); ++count) {
            auto callback = schedulerCallbacks_.front();
            schedulerCallbacks_.pop();
            jsEngine_->call(callback, jsEngine_->newUndefined(), {});
            jsEngine_->freeHandle(callback);
            processMicrotasks();
            if (std::chrono::steady_clock::now() >= deadline) break;
        }
    }

