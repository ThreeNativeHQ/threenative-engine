    void setupProcess() {
        if (!jsEngine_) return;

        // Create Node.js-compatible process object
        auto process = jsEngine_->newObject();

        // process.exit(code) - cleanly exit the application
        jsEngine_->setProperty(process, "exit",
            jsEngine_->newFunction("exit", [this](void* ctx, const std::vector<js::JSValueHandle>& args) {
                int exitCode = 0;
                if (!args.empty()) {
                    exitCode = static_cast<int>(jsEngine_->toNumber(args[0]));
                }
                std::cout << "[Mystral] process.exit(" << exitCode << ") called" << std::endl;
                exitCode_ = exitCode;
                running_ = false;
                return jsEngine_->newUndefined();
            })
        );

        // process.platform - useful for platform-specific code
#if defined(__ANDROID__)
        jsEngine_->setProperty(process, "platform", jsEngine_->newString("android"));
#elif defined(__APPLE__) && TARGET_OS_IPHONE
        jsEngine_->setProperty(process, "platform", jsEngine_->newString("ios"));
#elif defined(__APPLE__)
        jsEngine_->setProperty(process, "platform", jsEngine_->newString("darwin"));
#elif defined(_WIN32)
        jsEngine_->setProperty(process, "platform", jsEngine_->newString("win32"));
#elif defined(__linux__)
        jsEngine_->setProperty(process, "platform", jsEngine_->newString("linux"));
#else
        jsEngine_->setProperty(process, "platform", jsEngine_->newString("unknown"));
#endif

        // process.argv - command line arguments (placeholder for now)
        auto argv = jsEngine_->newArray();
        jsEngine_->setProperty(process, "argv", argv);

        // process.env - the launch flags a game may read.
        //
        // Only the flags a host chooses to publish: handing over the whole environment would put
        // the machine's variables in a game's hands, which is a leak nobody asked for. `DEV_MODE`
        // is the one a developer sets on the command line to ask for the dev surfaces, and the
        // engine reads it to decide whether they exist at all.
        auto env = jsEngine_->newObject();
        const char* devMode = std::getenv("DEV_MODE");
        if (devMode != nullptr && devMode[0] != '\0' && std::strcmp(devMode, "0") != 0 &&
            std::strcmp(devMode, "false") != 0) {
            jsEngine_->setProperty(env, "DEV_MODE", jsEngine_->newString("true"));
        }
        // The engine's own launch diagnostics, each off unless asked for. Forwarded verbatim
        // rather than as booleans so the engine's reader stays the single place that decides what
        // counts as on, and a host that publishes a flag never decides it twice. Listed rather
        // than pattern-matched on a prefix: publishing every `TN_*` variable a machine happens to
        // carry is a leak, and one line per flag is the price of not having one.
        for (const char* flag : {"TN_FRAME_SPANS", "TN_RENDERLIST_VALIDATE"}) {
            const char* value = std::getenv(flag);
            if (value != nullptr && value[0] != '\0') {
                jsEngine_->setProperty(env, flag, jsEngine_->newString(value));
            }
        }
        // The engine's debug switches, every `TN_DEBUG_*` variable, for `debugFlag()`. A prefix
        // rather than the two named flags above because the set is open — a game reads
        // `TN_DEBUG_` plus whatever it named its own switch — and a prefix is safe to forward where
        // a `TN_*` glob is not: this is a namespace only a developer sets on purpose, so no
        // variable a machine carries for itself can land in a game's hands through it.
        for (char** entry = tnEnviron(); entry != nullptr && *entry != nullptr; ++entry) {
            const char* value = std::strchr(*entry, '=');
            if (value == nullptr || std::strncmp(*entry, "TN_DEBUG_", 9) != 0) continue;
            const std::string name(*entry, static_cast<size_t>(value - *entry));
            jsEngine_->setProperty(env, name.c_str(), jsEngine_->newString(value + 1));
        }
        jsEngine_->setProperty(process, "env", env);

        jsEngine_->setGlobalProperty("process", process);
    }

