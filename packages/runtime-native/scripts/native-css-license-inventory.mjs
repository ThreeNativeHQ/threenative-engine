#!/usr/bin/env node
// Licence inventory for the native-css backend's Rust dependency closure.
//
// `cargo metadata --locked` on native/css-ui lists every crate the static library links, with the
// SPDX expression each declares. Output is deterministic (sorted, no timestamps, no absolute paths)
// so `--check` can fail on drift; it covers the declared licences only and is not a legal review.
// Usage: node scripts/native-css-license-inventory.mjs [--check]   Output: docs/verification/native-css-license-inventory.md

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const crate = join(here, "..", "native", "css-ui");
const output = resolve(here, "..", "..", "..", "docs", "verification", "native-css-license-inventory.md");

function metadata() {
  const run = spawnSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    cwd: crate,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  if (run.status !== 0) {
    throw new Error(`TN_NATIVE_CSS_LICENSE_METADATA: cargo metadata failed: ${run.stderr.trim().slice(0, 400)}`);
  }
  return JSON.parse(run.stdout);
}

export function render(meta) {
  const own = "threenative-css-ui";
  const rows = meta.packages
    .filter((p) => p.name !== own)
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? "UNDECLARED",
      // A path source is vendored in this repository (patched upstream); a registry source is not.
      vendored: p.source === null,
    }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const undeclared = rows.filter((r) => r.license === "UNDECLARED");
  // An expression that offers a permissive alternative (`MIT OR ... OR MPL-2.0`) is not a copyleft crate.
  const permissiveChoice = (l) => / OR /u.test(l) && /\b(MIT|Apache-2\.0)\b/u.test(l.split(" AND ")[0] ?? l);
  const copyleft = rows.filter((r) => /MPL|GPL|LGPL|EPL|CDDL/u.test(r.license) && !permissiveChoice(r.license));
  const byLicense = new Map();
  for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);
  const lines = [
    "# native-css licence inventory",
    "",
    "Generated by `node packages/runtime-native/scripts/native-css-license-inventory.mjs` from",
    "`cargo metadata --locked` on `packages/runtime-native/native/css-ui`. Declared SPDX expressions",
    "only; this is an inventory, not a legal review. The crates are statically linked into the host",
    "only when it is built with `TN_ENABLE_CSS_UI=1`; a default build links none of them.",
    "",
    `**${rows.length} crates**, ${undeclared.length} with no declared licence, ${copyleft.length} under a file-level copyleft licence.`,
    "",
    "## Needs a decision before shipping a CSS-enabled binary",
    "",
    copyleft.length === 0
      ? "None."
      : [
          "These crates are under MPL-2.0 (file-level copyleft). Static linking into a distributed binary",
          "obliges the distributor to make the source of the MPL-covered files available and to keep their",
          "notices; it does not extend to the rest of the host. Stylo is the CSS engine itself, so this",
          "cannot be avoided while `native-css` uses Blitz.",
          "",
          ...copyleft.map((r) => `- \`${r.name}\` ${r.version} — ${r.license}`),
        ].join("\n"),
    "",
    "## Patched copies kept in this repository",
    "",
    "Vendored under `native/css-ui/vendor/` (see `vendor/PATCHES.md`; upstream licence files kept):",
    "",
    ...rows.filter((r) => r.vendored).map((r) => `- \`${r.name}\` ${r.version} — ${r.license}`),
    "",
    "## By licence",
    "",
    "| Declared licence | Crates |",
    "| --- | ---: |",
    ...[...byLicense].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([l, n]) => `| ${l} | ${n} |`),
    "",
    "## Every crate",
    "",
    "| Crate | Version | Declared licence |",
    "| --- | --- | --- |",
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(metadata());
  if (process.argv.includes("--check")) {
    const current = existsSync(output) ? readFileSync(output, "utf8") : "";
    if (current !== text) {
      console.error("TN_NATIVE_CSS_LICENSE_DRIFT: regenerate with node packages/runtime-native/scripts/native-css-license-inventory.mjs");
      process.exit(1);
    }
    console.log("native-css licence inventory is current");
  } else {
    writeFileSync(output, text);
    console.log(`wrote ${output}`);
  }
}
