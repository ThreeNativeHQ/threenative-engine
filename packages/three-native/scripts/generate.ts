/**
 * Generates the public TypeScript declarations and the C binding ABI header from the catalog.
 *
 * Generation adapts names and shapes. It implements no algorithm and reads no reference
 * declaration: `api/catalog.json` is the contract, and everything below is spelling.
 *
 *   pnpm --filter @threenative/three-native generate
 */

